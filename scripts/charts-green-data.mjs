const RFI_ACTIONS = [
  { id: 'raise', label: 'Открываем всегда', color: '#d32f2f' },
  { id: 'raise_situational', label: 'Открываем в подходящих ситуациях', color: '#f9a825' },
]

function rfiChart(id, title, position, raiseDefs, situationalDefs) {
  return {
    id,
    title,
    position,
    situation: 'Open Raise (RFI)',
    sourcePage: 'GreenCharts2024_01-4.pdf',
    actions: RFI_ACTIONS,
    solution: mergeSolutions(
      toSolution(handList(raiseDefs), 'raise'),
      toSolution(handList(situationalDefs), 'raise_situational'),
    ),
  }
}

